export function findRecipe(slug) {
  return recipes.find((recipe) => recipe && recipe.slug === slug);
}

export function recipeSeoTitle(recipe) {
  if (recipe.seoTitle) return recipe.seoTitle;
  const minutes = recipe.prepMinutes + recipe.cookMinutes;
  return `${recipe.title} Recipe (${minutes}-Minute)`;
}

export function relatedRecipes(recipe, limit = 3) {
  const sameCategory = recipes.filter(
    (item) => item.slug !== recipe.slug && item.category === recipe.category
  );
  if (sameCategory.length >= limit) return sameCategory.slice(0, limit);
  const rest = recipes.filter(
    (item) => item.slug !== recipe.slug && item.category !== recipe.category
  );
  return [...sameCategory, ...rest].slice(0, limit);
}
